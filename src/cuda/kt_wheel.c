/*
 * kt_wheel.c - admissibility-wheel CRT-join builder (Phase 3b).
 *
 * Pure C (compiles with cc -O3 -std=c11). See kt_wheel.h for the API.
 *
 * Algorithm follows the project's CRT-join wheel model:
 *   For each q in prime_list:
 *     immune = [0..q-1] \ F_q
 *     if |immune| == 0: pattern inadmissible at q -> return -2
 *     wheel = CRT-extend(wheel, m, q, immune)   (sorted, deduped)
 *     m *= q
 *   FNV-1a-64 the final sorted offsets to detect drift vs GP canonical.
 *
 * The kt_canonical_wheel_hashes[] table at the bottom of this file is the
 * ground truth, regenerated by `make canonical-hashes` from the self-contained
 * GP parity tool.
 */

