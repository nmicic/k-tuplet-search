const kt_canonical_wheel_t *kt_wheel_canonical_lookup(
    const char *pattern_name,
    const uint32_t *prime_list, int n_primes) {
    if (!pattern_name || !prime_list || n_primes <= 0) return NULL;
    for (int i = 0; i < kt_canonical_wheel_hashes_count; i++) {
        const kt_canonical_wheel_t *e = &kt_canonical_wheel_hashes[i];
        if (!e->pattern_name) continue;
        if (strcmp(e->pattern_name, pattern_name) != 0) continue;
        if (e->n_primes != n_primes) continue;
        int match = 1;
        for (int j = 0; j < n_primes; j++) {
            if (e->primes[j] != prime_list[j]) { match = 0; break; }
        }
        if (match) return e;
    }
    return NULL;
}

